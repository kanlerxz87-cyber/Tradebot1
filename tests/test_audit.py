"""Regression tests for the defects found by the 2026-11-22 line-by-line audit.

Each test names the official page it enforces and the audit item it closes.
Audit page: docs/audit/ (generated by audit/build_site.py).
"""

from __future__ import annotations

from kalshi_trader.collector import _collect_resolutions
from kalshi_trader.marketdata import normalize_market

# The shape every one of the eight markets in data/snapshot.json has: a real YES bid,
# a NO side with no resting orders, and yes_ask_dollars reported as 1.0000.
EMPTY_NO_SIDE = {
    "ticker": "KXELONMARS-99",
    "event_ticker": "KXELONMARS-99",
    "status": "active",
    "yes_bid_dollars": "0.1400",
    "yes_ask_dollars": "1.0000",
    "no_bid_dollars": "0.0000",
    "no_ask_dollars": "0.8600",
    "last_price_dollars": "0.3000",
    "volume_fp": "14150.08",
    "volume_24h_fp": "6.15",
    "open_interest_fp": "12774.79",
    "yes_bid_size_fp": "2718.76",
    "yes_ask_size_fp": "0.00",
    "result": "",
}

TWO_SIDED = {
    **EMPTY_NO_SIDE,
    "ticker": "TWO-SIDED",
    "yes_bid_dollars": "0.4000",
    "yes_ask_dollars": "0.4400",
    "no_bid_dollars": "0.5600",
    "no_ask_dollars": "0.6000",
    "last_price_dollars": "0.4200",
}


def test_empty_side_is_not_an_ask():
    """AUD-02: an ask of 1.0000 with no NO bid is the empty-side sentinel.

    https://docs.kalshi.com/getting_started/orderbook_responses
    """
    row = normalize_market(EMPTY_NO_SIDE)
    assert row["yes_ask"] is None
    assert row["spread"] is None


def test_empty_side_midpoint_falls_back_to_last_trade():
    """The midpoint must not be (0.14 + 1.00) / 2 = 0.57."""
    row = normalize_market(EMPTY_NO_SIDE)
    assert row["mid"] == 0.30
    assert row["price"] == 0.30


def test_two_sided_book_midpoint_unchanged():
    row = normalize_market(TWO_SIDED)
    assert row["yes_ask"] == 0.44
    assert row["mid"] == 0.42
    assert row["spread"] == 0.04


def test_zero_dollar_quote_does_not_fall_back_to_legacy_cents():
    """AUD-12: a real 0.0000 dollar quote must stay 0.0 rather than falling through to cents."""
    row = normalize_market({"ticker": "ZERO-1", "yes_bid_dollars": "0.0000", "yes_bid": 42})
    assert row["yes_bid"] == 0.0


class RecordingClient:
    """Minimal stand-in that records the query each sweep sends."""

    def __init__(self):
        self.calls = []

    def paginate(self, path, key, params, *, page_size=100, max_pages=1):
        self.calls.append((path, dict(params)))
        return []


def test_settled_sweep_uses_min_settled_ts():
    """AUD-03: GET /markets pairs status=settled with min_settled_ts, not min_close_ts.

    https://docs.kalshi.com/api-reference/market/get-markets
    """
    client = RecordingClient()
    errors: list[str] = []
    _collect_resolutions(client, {}, {"crypto": ["KXBTCD"]}, [], errors, now=0)
    assert errors == []
    assert len(client.calls) == 1
    _, params = client.calls[0]
    assert params["status"] == "settled"
    assert "min_settled_ts" in params
    assert "min_close_ts" not in params
    assert isinstance(params["min_settled_ts"], int)


def test_settled_sweep_is_bounded_and_reports_errors():
    class Boom(RecordingClient):
        def paginate(self, *a, **k):
            raise RuntimeError("upstream down")

    errors: list[str] = []
    rows = _collect_resolutions(Boom(), {}, {"crypto": ["KXBTCD"]}, [], errors, now=0)
    assert rows == []
    assert errors and errors[0].startswith("settled KXBTCD:")


# ---------------------------------------------------------------- audit gates
import shutil

import pytest


def _audit_module():
    import importlib.util
    from pathlib import Path

    path = Path(__file__).resolve().parent.parent / "audit" / "verify.py"
    spec = importlib.util.spec_from_file_location("audit_verify", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_audit_register_is_internally_consistent():
    if shutil.which("node") is None:
        pytest.skip("node is required to re-execute the audit's JavaScript checks")
    doc = _audit_module().build()
    ids = [item["id"] for item in doc["items"]]
    assert len(ids) == len(set(ids))
    assert doc["meta"]["factCount"] == len(doc["facts"])
    for item in doc["items"]:
        assert item["sources"] or item["repoSources"], item["id"]
        if not item["sources"]:
            # A finding with no official page behind it must say why, rather than
            # borrowing a source that does not decide it.
            assert item.get("noOfficialSource"), item["id"]
        for source in item["sources"]:
            assert source["url"].startswith("https://")
        for evidence in item["evidence"]:
            assert evidence["line"] >= 1


def test_every_audit_check_agrees_with_its_published_status():
    if shutil.which("node") is None:
        pytest.skip("node is required to re-execute the audit's JavaScript checks")
    doc = _audit_module().build()
    for item in doc["items"]:
        if item["status"] in {"fixed", "open"}:
            assert item["check"]["ok"], f"{item['id']} contradicts its own status"
